$diagramSvg = [Text.StringBuilder]::new()
function Add-Svg([string]$value) { [void]$diagramSvg.AppendLine($value) }
function Escape-Xml([string]$value) { [Security.SecurityElement]::Escape($value) }
function Add-Text([int]$x, [int]$y, [string]$value, [string]$class) {
    Add-Svg ('<text x="{0}" y="{1}" class="{2}">{3}</text>' -f $x, $y, $class, (Escape-Xml $value))
}
function Split-DiagramText([string]$value) {
    # Переносим по словам, чтобы длинные условия и действия оставались внутри дуги.
    $line = ''
    foreach ($word in ($value -split ' ')) {
        if ($line.Length + $word.Length -gt 130) {
            $line
            $line = $word
        } else {
            if ($line) { $line += ' ' }
            $line += $word
        }
    }
    if ($line) { $line }
}
